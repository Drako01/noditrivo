const catalogs = { en, es } as const;

export type Locale = keyof typeof catalogs;
export type MessageParams = Readonly<Record<string, string | number>>;

export const resolveLocale = (language: string): Locale => (language.toLowerCase().startsWith('es') ? 'es' : 'en');

export function translate(locale: Locale, key: MessageKey, params: MessageParams = {}): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (_match, name: string) => {
    const value = params[name];
    if (value === undefined) throw new Error(`Missing i18n parameter "${name}" for "${key}".`);
    return String(value);
  });
}
